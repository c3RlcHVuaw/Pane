def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write():
    out = os.path.join(ROOT, "Resources", "ru.lproj")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/strings_ru.py — edit the dictionary there. */\n")
        for k, v in RU.items():
            f.write('"%s" = "%s";\n' % (esc(k), esc(v)))
    with open(os.path.join(out, "InfoPlist.strings"), "w", encoding="utf-8") as f:
        f.write('"NSMicrophoneUsageDescription" = "Pane использует микрофон для диктовки в ассистенте и когда этого просит страница.";\n')
        f.write('"NSSpeechRecognitionUsageDescription" = "Pane превращает вашу речь в текст для ассистента.";\n')
    print("wrote", len(RU), "strings")


def check():
    pat = re.compile(r'(?:\btr\(|String\(localized:\s*)"((?:[^"\\\n]|\\.)*)"')
    missing = set()
    for p in glob.glob(os.path.join(ROOT, "Sources", "**", "*.swift"), recursive=True):
        for m in pat.finditer(open(p, encoding="utf-8").read()):
            k = re.sub(r"\\\((?:[^()]|\([^()]*\))*\)", "%@", m.group(1))
            if "\\(" in k or k.endswith(("[", '"')): continue
            if k not in RU:
                missing.add(k)
    for k in sorted(missing):
        print(k)
    print(len(missing), "untranslated", file=sys.stderr)


if __name__ == "__main__":
    {"write": write, "check": check}.get(sys.argv[1] if len(sys.argv) > 1 else "write", write)()
